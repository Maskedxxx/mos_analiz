#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Препроцессор для Приказа о проведении выхода (prikaz_vyhod).

normalize_text_for_rule3 — заменяет вариативные плейсхолдеры (должность + ФИО)
в пунктах 1 и 2 приказа на унифицированную метку [ДОЛЖНОСТЬ_ФИО],
чтобы сравнение с шаблоном фиксированного текста работало корректно.
"""

import re

from .registry import register_preprocessor


@register_preprocessor("prikaz_vyhod", "текст_приказа")
def normalize_text_for_rule3(text: str) -> str:
    """
    Нормализует текст приказа для сравнения с шаблоном (правило #3).

    Заменяет:
    - п.1: "Назначить организатором...площадке <должность ФИО>." → [ДОЛЖНОСТЬ_ФИО]
    - п.2: "Назначить секретарем...площадке <должность ФИО>." → [ДОЛЖНОСТЬ_ФИО]

    ВАЖНО: используем DOTALL + non-greedy (.+?) с остановкой на границе абзаца,
    чтобы не съесть следующие пункты приказа (баг со старым жадным .+\. + DOTALL).
    """
    # п.1: должность + ФИО организатора
    # «площадке» — с опциональным «производственной» (в некоторых документах без него)
    # Остановка: пустая строка (\n\n), следующий пункт (\n\d+.) или конец текста
    text = re.sub(
        r'(1\.\s*Назначить организатором проведения обхода на\s+'
        r'(?:производственной\s+)?площадке\s+)'
        r'(.+?)'
        r'(?=\s*\n\s*\n|\s*\n\s*\d+\.|\s*$)',
        r'\1[ДОЛЖНОСТЬ_ФИО].',
        text,
        flags=re.DOTALL
    )

    # п.2: должность + ФИО секретаря
    text = re.sub(
        r'(2\.\s*Назначить секретарем проведения обхода на\s+'
        r'(?:производственной\s+)?площадке\s+)'
        r'(.+?)'
        r'(?=\s*\n\s*\n|\s*\n\s*\d+\.|\s*$)',
        r'\1[ДОЛЖНОСТЬ_ФИО].',
        text,
        flags=re.DOTALL
    )

    return text


@register_preprocessor("prikaz_vyhod", "заголовок_город")
def normalize_header(text: str) -> str:
    """
    Нормализует заголовок для сравнения с шаблоном (правило #1).

    «П Р И К А З» (разреженное написание) → «Приказ» (как в шаблоне).
    gpt-4.1-mini игнорирует инструкцию в промпте, поэтому нормализуем до LLM.
    """
    text = re.sub(r'П\s+Р\s+И\s+К\s+А\s+З', 'Приказ', text)
    return text
