#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Препроцессор для Приказа о проведении выхода (prikaz_vyhod).

normalize_text_for_rule3 — заменяет вариативные плейсхолдеры (должность + ФИО)
в пунктах 1 и 2 приказа на унифицированную метку [ДОЛЖНОСТЬ_ФИО],
чтобы сравнение с шаблоном фиксированного текста работало корректно.
"""

import re

from .registry import register_preprocessor


@register_preprocessor("prikaz_vyhod", "текст_приказа")
def normalize_text_for_rule3(text: str) -> str:
    """
    Нормализует текст приказа для сравнения с шаблоном (правило #3).

    Заменяет:
    - п.1: "Назначить организатором...площадке <должность ФИО>." → [ДОЛЖНОСТЬ_ФИО]
    - п.2: "Назначить секретарем...площадке <должность ФИО>." → [ДОЛЖНОСТЬ_ФИО]
    """
    # п.1: должность + ФИО организатора
    text = re.sub(
        r'(1\.\s*Назначить организатором проведения обхода на производственной площадке\s*).+?\.',
        r'\1[ДОЛЖНОСТЬ_ФИО].',
        text,
        flags=re.DOTALL
    )

    # п.2: должность + ФИО секретаря
    text = re.sub(
        r'(2\.\s*Назначить секретарем проведения обхода на производственной площадке\s*).+?\.',
        r'\1[ДОЛЖНОСТЬ_ФИО].',
        text,
        flags=re.DOTALL
    )

    return text
