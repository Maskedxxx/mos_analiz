#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Препроцессор для Приказа о проведении конкурсов ППУ (prikaz_comp_ppu).

normalize_text_for_rule3 — вырезает из текста приказа ТОЛЬКО тело:
  преамбула («С целью...») + «ПРИКАЗЫВАЮ:» + нумерованные пункты.
  Шапка (юрлицо, ПРИКАЗ №, город, дата) и подписант удаляются.
  Плейсхолдеры ФИО/должности нормализуются в [ДОЛЖНОСТЬ_ФИО].
"""

import re

from .registry import register_preprocessor


@register_preprocessor("prikaz_comp_ppu", "текст_приказа")
def normalize_text_for_rule3(text: str) -> str:
    """
    Извлекает чистый текст приказа для сравнения с шаблоном (правило #3).

    Вход: полный текст страницы (шапка + заголовок + преамбула + пункты + подписант).
    Выход: от преамбулы «С целью...»/«В целях...» до последнего нумерованного пункта.

    Работает одинаково для таргета и шаблона — обе стороны получают
    идентичную структуру без шапки и подписанта.
    """
    lines = text.strip().split('\n')

    # Ищем начало: первая строка с преамбулой
    start_idx = None
    for i, line in enumerate(lines):
        s = line.strip()
        if s.startswith('С целью') or s.startswith('В целях'):
            start_idx = i
            break
        # Fallback: если преамбулы нет, начинаем с ПРИКАЗЫВАЮ
        if s == 'ПРИКАЗЫВАЮ:':
            start_idx = i
            break

    if start_idx is None:
        start_idx = 0

    # Ищем конец: последняя строка начинающаяся с номера пункта (N.)
    end_idx = len(lines) - 1
    for i in range(len(lines) - 1, -1, -1):
        s = lines[i].strip()
        if re.match(r'^\d+\.', s):
            end_idx = i
            break

    # Вырезаем только тело приказа
    body = '\n'.join(lines[start_idx:end_idx + 1])

    # Нормализуем плейсхолдеры ФИО/должность → единый формат
    # Target: «возложить на Рассейкина В.А., заместителя руководителя.»
    # Template: «возложить на <ФИО> и <должность>»
    # Жадный .+ чтобы матчить до ПОСЛЕДНЕЙ точки (не первой — инициалы А.)
    body = re.sub(
        r'(возложить на\s*).+\.',
        r'\1[ДОЛЖНОСТЬ_ФИО].',
        body
    )
    # Шаблонный формат: <ФИО> и <должность>
    body = re.sub(
        r'(возложить на\s*)<[^>]+>\s*и\s*<[^>]+>',
        r'\1[ДОЛЖНОСТЬ_ФИО].',
        body
    )

    return body
