#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Препроцессоры для Положений (polozhenie_comp_ppu, polozhenie_ppu).

preprocess_shapka — нормализует шапку:
  1) Удаляет дублирующиеся строки (артефакт Vision Parser)
  2) Склеивает «к приказу от <дата>\n№ <номер>» в одну строку
normalize_text — нормализует основной текст для сравнения с шаблоном:
  1) Заменяет ФИО (Фамилия И.О.) → [ФИО]
  2) Заменяет блок «ФИО-Должность - председателя» → [ДОЛЖНОСТЬ_ФИО] - председателя
  3) Нормализует множественные переносы строк (\n\n → \n)
  4) Удаляет номера страниц (артефакт Vision)
  5) Склеивает строки-продолжения (артефакт границы страниц)
"""

import re

from .registry import register_preprocessor


@register_preprocessor("polozhenie_comp_ppu", "шапка")
@register_preprocessor("polozhenie_ppu", "шапка")
def preprocess_shapka(text: str) -> str:
    """
    Нормализует шапку:
    1) Удаляет дублирующийся хвост (Vision Parser иногда дублирует текст)
    2) Склеивает строку 'к приказу от <дата>' со строкой '№ <номер>'
       Vision иногда разбивает на 2 строки: 'от 13.11.2025г.\n№ 10БП'
       Шаблон содержит их в одной строке: 'от <...> № <...>'
    """
    # --- Шаг 1: Удаление дублирующего хвоста ---
    lines = text.split('\n')

    # Собираем непустые строки с их индексами
    non_empty = [(i, l.strip()) for i, l in enumerate(lines) if l.strip()]

    if len(non_empty) >= 3:
        # Пробуем разные длины хвоста (от половины до 1)
        for tail_len in range(len(non_empty) // 2, 0, -1):
            tail_texts = [t for _, t in non_empty[-tail_len:]]

            # Ищем этот хвост среди ранних строк
            for start in range(len(non_empty) - tail_len):
                match = all(
                    non_empty[start + j][1] == tail_texts[j]
                    for j in range(tail_len)
                )
                if match:
                    # Нашли дубль — обрезаем
                    cut_line = non_empty[-tail_len][0]
                    while cut_line > 0 and not lines[cut_line - 1].strip():
                        cut_line -= 1
                    text = '\n'.join(lines[:cut_line])
                    break
            else:
                continue
            break

    # --- Шаг 2: Нормализация пустых строк ---
    # Vision иногда вставляет лишние пустые строки
    text = re.sub(r'\n{2,}', '\n', text)

    # --- Шаг 3: Удаление строки «к приказу от ... № ...» ---
    # Эта строка содержит даты/номера — переменные значения.
    # Её проверяет правило #5 (target_only). Для сравнения с шаблоном (правило #1)
    # она только мешает. Удаляем из обоих текстов.
    # Сначала склеиваем разбитые строки (Vision артефакт), потом удаляем всю строку
    text = re.sub(r'(к приказу от[^\n]*?)\s*\n\s*(№)', r'\1 \2', text)
    text = re.sub(r'к приказу от[^\n]*\n?', '', text)
    # Удалить номер из «Приложение №1» — оставить только слово «Приложение»
    text = re.sub(r'(приложение)\s*№\s*\S*', r'\1', text, flags=re.IGNORECASE)

    # --- Шаг 4: Обрезка тела документа ---
    # Vision иногда включает текст разделов (1. Общие положения...) в шапку.
    # Шапка — только «Приложение» + название документа.
    # Отсекаем всё начиная с первого заголовка раздела (N. Текст)
    text = re.sub(r'\n\d+\.\s+.*', '', text, flags=re.DOTALL)

    # --- Шаг 5: Нормализация регистра ---
    # Vision иногда извлекает «ПОЛОЖЕНИЕ» vs «Положение» — разный регистр
    # Для сравнения структуры шапки регистр не важен
    text = text.lower()

    return text


@register_preprocessor("polozhenie_comp_ppu", "структура_разделов")
@register_preprocessor("polozhenie_ppu", "структура_разделов")
def normalize_structure(text: str) -> str:
    """
    Нормализует структуру разделов:
    1) Добавляет точку после голого номера раздела: '5 Порядок' → '5. Порядок'
       Vision иногда теряет точку при извлечении заголовков.
       НЕ затрагивает подразделы (2.2, 3.4.1) — у них уже есть точки.
    2) Убирает пустые строки
    """
    # Голый номер без точки перед текстом → добавить точку
    text = re.sub(r'^(\d+)[ \t]+', r'\1. ', text, flags=re.MULTILINE)
    # Убрать пустые строки
    text = re.sub(r'\n{2,}', '\n', text)

    # Оставить ТОЛЬКО разделы верхнего уровня (1., 2., 3., 4., 5.)
    # Подразделы (2.2, 3.4, 4.2.4) убираем — они проверяются правилом #4
    lines = text.strip().split('\n')
    top_level = [l for l in lines if re.match(r'^\d+\.\s', l)]
    if top_level:
        text = '\n'.join(top_level)

    return text


@register_preprocessor("polozhenie_comp_ppu", "основной_текст")
@register_preprocessor("polozhenie_ppu", "основной_текст")
def normalize_text(text: str) -> str:
    """
    Нормализует основной текст для сравнения с шаблоном.

    1) Заменяет блок «...на ФИО-Должность - председателя» на тег
       (и шаблон «на должность - председателя» тоже)
    2) Заменяет ФИО вида «Фамилия И.О.» на [ФИО]
    3) Нормализует множественные \n → один \n
    """
    # 1. П.3.1: «возлагается на <ФИО-Должность> - председателя» → тег
    #    Работает и для шаблона: «на должность - председателя»
    #    и для таргета: «на Иванов И.И.- Специалиста... - председателя»
    text = re.sub(
        r'возлагается на .+?[ \t]*-[ \t]*председателя',
        'возлагается на [ДОЛЖНОСТЬ_ФИО] - председателя',
        text
    )

    # 2. Замена ФИО — «Фамилия И.О.» и «И.О. Фамилия»
    # Фамилия И.О. (например: Иванов И.И., Петрова А.Б.)
    text = re.sub(
        r'[А-ЯЁ][а-яё]+\s+[А-ЯЁ]\.[А-ЯЁ]\.',
        '[ФИО]',
        text
    )
    # И.О. Фамилия (например: И.И. Иванов)
    text = re.sub(
        r'[А-ЯЁ]\.[А-ЯЁ]\.\s+[А-ЯЁ][а-яё]+',
        '[ФИО]',
        text
    )

    # 3. Нормализация переносов: \n\n+ → \n
    text = re.sub(r'\n{2,}', '\n', text)

    # 3.5. Нормализация номеров разделов: '5 Порядок' → '5. Порядок'
    #      Vision иногда теряет точку. НЕ затрагивает подразделы (2.2, 3.4.1)
    text = re.sub(r'^(\d+)[ \t]+', r'\1. ', text, flags=re.MULTILINE)

    # 4. Удаление номеров страниц (артефакт Vision Parser)
    #    Vision вставляет голые цифры (2, 3, 4, 5) на границах страниц
    #    Паттерн: строка из 1-2 цифр без точки и текста
    #    НЕ затрагивает: «2.1», «3.4.1», «4.\tКачество» — у них есть точка/текст
    lines_filtered = text.split('\n')
    text = '\n'.join(l for l in lines_filtered if not re.match(r'^\d{1,2}$', l.strip()))

    # 5. Удаление дублей заголовков таблиц (артефакт Vision на границе страниц)
    #    Vision дублирует «№ п/п\tКатегория\tПредложения» при конкатенации страниц
    seen_table_headers = set()
    deduped_lines = []
    for line in text.split('\n'):
        stripped = line.strip()
        if stripped.startswith('№ п/п'):
            if stripped in seen_table_headers:
                continue  # Дубль — пропускаем
            seen_table_headers.add(stripped)
        deduped_lines.append(line)
    text = '\n'.join(deduped_lines)

    # 6. Склейка строк-продолжений (артефакт Vision на границе страниц)
    #    Vision иногда разбивает фразу: «может иметь\nместо» → «может иметь место»
    #    Правило: если строка начинается с маленькой буквы
    #    и предыдущая не заканчивается на .;: → склеиваем
    lines = text.split('\n')
    merged = []
    for line in lines:
        stripped = line.strip()
        if (merged and stripped and
                not re.match(r'^\d', stripped) and
                stripped[0].islower() and
                merged[-1].strip() and
                merged[-1].strip()[-1] not in '.;:'):
            # Продолжение предыдущей строки — склеиваем
            merged[-1] = merged[-1].rstrip() + ' ' + stripped
        else:
            merged.append(line)
    text = '\n'.join(merged)

    # 7. Разбиение склеенных пунктов списка: '; текст' → '.\nтекст'
    #    Vision иногда склеивает пункты списка в одну строку через ';'
    #    Шаблон имеет их как отдельные строки с '.'
    #    Паттерн: '; ' + маленькая буква → разбить на строки
    text = re.sub(r';[ \t]+([а-яё])', r'.\n\1', text)

    # 7.5. Нормализация пунктуации в конце строк: ';' → '.'
    #      В списках/определениях ';' и '.' стилистически взаимозаменяемы.
    #      gpt-4.1-mini ловит это как нарушение даже с НОРМА-инструкцией в промпте.
    text = re.sub(r';(\s*)$', r'.\1', text, flags=re.MULTILINE)

    # 8. Нормализация слитного/раздельного «не»: «не денежной» → «неденежной»
    #    Применяется к ОБОИМ текстам — безопасно, т.к. корректность русского
    #    не важна для сравнения, важна только одинаковость обработки.
    #    «не может» → «неможет» в обоих текстах — равенство сохраняется.
    text = re.sub(r'\bне\s+([а-яё])', r'не\1', text)

    return text
