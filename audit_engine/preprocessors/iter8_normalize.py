# -*- coding: utf-8 -*-
"""
Препроцессор для документов итерации 8 (Положение о ПО, Приказ о формировании ПО).

Нормализует текст перед template-сравнением:
- Убирает аннотации менеджера (- заголовок, - дата)
- Заменяет даты, ФИО, организации, номера на унифицированные метки
- Маскирует плейсхолдеры (подчёркивания) и конкретные значения одинаково

Это позволяет LLM сравнивать СТРУКТУРУ текста, а не конкретные данные.
"""

import re

from .registry import register_preprocessor


def normalize_text_for_comparison(text: str) -> str:
    """
    Нормализует текст перед сравнением с шаблоном.

    Заменяет переменные данные (даты, ФИО, организации) на метки [ДАТА], [ФИО] и т.д.
    Применяется и к целевому документу, и к шаблону.
    """
    # 0. Убираем аннотации менеджера (текст после тире в конце строки)
    text = re.sub(r'\s*-\s*[а-яё\s]+$', '', text, flags=re.MULTILINE | re.IGNORECASE)
    text = re.sub(
        r'\s*-\s*(заголовок|дата|номер|форма|место|подпись).*$',
        '', text, flags=re.MULTILINE | re.IGNORECASE
    )

    # 1. Нормализуем пробелы
    text = re.sub(r'[ \t]+', ' ', text)
    text = re.sub(r'\n\s*\n', '\n\n', text)

    # 2. Даты: конкретные и плейсхолдеры → [ДАТА]
    text = re.sub(r'\d{1,2}\.\d{1,2}\.\d{4}\s*г?\.?', '[ДАТА]', text)
    text = re.sub(r'«?\d{1,2}»?\s*[а-яё]+\s*\d{4}\s*г?\.?', '[ДАТА]', text, flags=re.IGNORECASE)
    text = re.sub(r'_{2,}\.\s*_{2,}\.\s*\d{4}|_{2,}\.\s*_{2,}\.\s*202_?', '[ДАТА]', text)

    # 2.1. "в срок до ___" / "в срок до 21.06.2025" → "в срок до [ДАТА]"
    text = re.sub(r'в срок до\s*_+\.?', 'в срок до [ДАТА]', text)
    text = re.sub(r'в срок до\s*\[ДАТА\]\.?', 'в срок до [ДАТА]', text)

    # 2.2. "срок ___" / "срок 21.06.2025" / "срок_24.07.2025" → "срок [ДАТА]"
    text = re.sub(r'срок\s*_*\d{1,2}\.\d{1,2}\.\d{4}\.?', 'срок [ДАТА]', text)
    text = re.sub(r'срок\s*_+\.?', 'срок [ДАТА]', text)
    text = re.sub(r'срок\s*\[ДАТА\]\.?', 'срок [ДАТА]', text)

    # 3. "Ответственный ___" / конкретная должность → "Ответственный [ДОЛЖНОСТЬ]"
    text = re.sub(r'Ответственный\s*_+', 'Ответственный [ДОЛЖНОСТЬ]', text)
    text = re.sub(r'Ответственный\s+([а-яёА-ЯЁ\s]+?)\s+срок', r'Ответственный [ДОЛЖНОСТЬ] срок', text)

    # 4. "руководителем ПО ___" / конкретное ФИО → "руководителем ПО [ФИО]"
    text = re.sub(r'руководителем ПО\s*_+', 'руководителем ПО [ФИО]', text)
    text = re.sub(r'руководителем ПО\s+[а-яёА-ЯЁ\s]+(?=\s+срок)', 'руководителем ПО [ФИО]', text)

    # 5. ФИО: Фамилия И.О. / И.О. Фамилия → [ФИО]
    text = re.sub(r'[А-ЯЁ][а-яё]+\s+[А-ЯЁ]\.[А-ЯЁ]\.', '[ФИО]', text)
    text = re.sub(r'[А-ЯЁ]\.[А-ЯЁ]\.\s*[А-ЯЁ][а-яё]+', '[ФИО]', text)
    text = re.sub(r'И\.О\.\s*Фамилия', '[ФИО]', text)
    text = re.sub(r'\(Фамилия И\.О\.\)', '', text)

    # 6. Организации: ООО "Название" / ООО «____» → [ОРГАНИЗАЦИЯ]
    text = re.sub(r'(ООО|ЗАО|АО|ПАО)\s*[«"][\w\s]+[»"]', '[ОРГАНИЗАЦИЯ]', text)
    text = re.sub(r'(ООО|ЗАО|АО|ПАО)\s*[«"]_+[»"]', '[ОРГАНИЗАЦИЯ]', text)

    # 7. Плейсхолдеры должностей
    text = re.sub(r'\(Указать наименование должности\)', '[ДОЛЖНОСТЬ]', text)

    # 8. Номера приказов: № 07, №___ → [НОМЕР]
    text = re.sub(r'№\s*\d+[а-яА-Я]*', '№ [НОМЕР]', text)
    text = re.sub(r'№\s*_+', '№ [НОМЕР]', text)

    # 9. Оставшиеся длинные подчёркивания → [ПЛЕЙСХОЛДЕР]
    text = re.sub(r'_+', '[ПЛЕЙСХОЛДЕР]', text)

    # 10. Дедупликация токенов
    text = re.sub(r'\[ДАТА\]\s*\[ДАТА\]', '[ДАТА]', text)
    text = re.sub(r'\[ФИО\]\s*\[ФИО\]', '[ФИО]', text)
    text = re.sub(r'\[ДОЛЖНОСТЬ\]\s*\[ДОЛЖНОСТЬ\]', '[ДОЛЖНОСТЬ]', text)

    return text.strip()


# ============================================================================
# Регистрация для polozhenie_po — все scope с compare=template
